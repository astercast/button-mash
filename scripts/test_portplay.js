/* PortPlay end-to-end proof suite.
   Run: node scripts/test_portplay.js

   Proves, per class, the claims the site makes:
   1. CONVERT: every converter profile validates a structurally real
      fixture with zero errors and builds a token-free portable file.
      The positive control is a real homebrew ROM (rkanoid).
   2. PLAY: every extension the router claims routes to play; the
      content-signature routes (CHD, Sega CD, PlayStation SYSTEM.CNF)
      route by bytes, not names.
   3. DECLINE: every system the site declines is reachable through a real
      detection route (signature, extension, or ISO contents), carries a
      tone, steps, and a guide link whose anchor exists in guide.html.
   4. ZIP + DOS: a stored zip round-trips and its contents route onward;
      a DOS folder is recognised and its start program chosen.
   5. COVERAGE: data/v1/coverage.json (generated by build.py from the
      engines) agrees with the engines this suite just exercised.
*/
