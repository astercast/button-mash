/* Minimal ISO9660 image builder (PVD + root dir + optional SYSTEM.CNF). */
function both32(buf, off, v) {
  buf.writeUInt32LE(v, off); buf.writeUInt32BE(v, off + 4);
}
function both16(buf, off, v) {
  buf.writeUInt16LE(v, off); buf.writeUInt16BE(v, off + 2);
}
function dirRecord(extent, size, flags, name) {
  const nameBuf = Buffer.from(name, "ascii");
  let len = 33 + nameBuf.length;
  if (nameBuf.length % 2 === 0) len += 1;
  const rec = Buffer.alloc(len);
  rec[0] = len; rec[1] = 0;
  both32(rec, 2, extent); both32(rec, 10, size);
  rec.set([126, 10, 15, 0, 0, 0, 0], 18);
  rec[25] = flags;
  both16(rec, 28, 1);
  rec[32] = nameBuf.length;
  nameBuf.copy(rec, 33);
  return rec;
}
function makeIso(entries, cnfText) {
  const buf = Buffer.alloc(0xE000);
  const pvd = 0x8000;
  buf[pvd] = 1; Buffer.from("CD001", "ascii").copy(buf, pvd + 1); buf[pvd + 6] = 1;
  const rootRec = dirRecord(20, 2048, 2, "\x00");
  rootRec.copy(buf, pvd + 156);
  let off = 0xA000; /* sector 20: root directory */
  dirRecord(20, 2048, 2, "\x00").copy(buf, off); off += 34;
  dirRecord(20, 2048, 2, "\x01").copy(buf, off); off += 34;
  for (const e of entries) {
    const r = dirRecord(e.extent || 22, e.size || 2048, e.flags, e.name);
    r.copy(buf, off); off += r.length;
  }
  if (cnfText) {
    const cnf = Buffer.from(cnfText, "ascii");
    const r = dirRecord(21, cnf.length, 0, "SYSTEM.CNF;1");
    r.copy(buf, off);
    cnf.copy(buf, 0xA800); /* sector 21 */
  }
  return U(buf);
}
