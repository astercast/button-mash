/* test_gamenight_parity.js — Wave B parity gate for "same function, two homes".
   Compares the server engine (lib/game-night.js, used by POST /api/game-night)
   against the browser twin (assets/js/game-night.js, regenerated by
   scripts/build.py, used by the party-planner client fallback) across an
   input battery. Any divergence fails the build contract: the fallback must
   compute exactly what the server would.
   Usage: node scripts/test_gamenight_parity.js   (exit 0 = parity holds) */
"use strict";

const fs = require("fs");
const path = require("path");
const vm = require("vm");

const ROOT = path.resolve(__dirname, "..");

// Server engine (CommonJS, as the function requires it).
const server = require(path.join(ROOT, "lib", "game-night.js"));

// Browser twin: evaluate in a sandbox with a fake window.
const twinSrc = fs.readFileSync(path.join(ROOT, "assets", "js", "game-night.js"), "utf8");
const sandbox = { window: {} };
vm.createContext(sandbox);
vm.runInContext(twinSrc, sandbox, { filename: "game-night.js" });
const client = sandbox.window.BMGameNight;

if (!client || typeof client.pickLineup !== "function") {
  console.error("FAIL: browser twin did not expose window.BMGameNight.pickLineup");
  process.exit(1);
}

// Real catalog, same construction as api/game-night.js. Static data lives
// in data/v1/ since wave 20 (Vercel never serves static files under api/);
// this suite kept the old path segments and died on ENOENT — fixed wave 22.
const gamesEnv = JSON.parse(fs.readFileSync(path.join(ROOT, "data", "v1", "games.json"), "utf8"));
const kidEnv = JSON.parse(fs.readFileSync(path.join(ROOT, "data", "v1", "kid-safe.json"), "utf8"));
const catalog = {
  games: gamesEnv.games || [],
  kidSafeIds: new Set((kidEnv["kid-safe"] || []).filter((k) => k.kid_safe).map((k) => k.id)),
  generated_at: gamesEnv.generated_at || null,
};

const VIBES = ["cozy", "chaotic", "competitive", "party", "chill"];
const cases = [];
for (const group_size of [1, 2, 4, 6, 12]) {
  for (const minutes of [15, 30, 60, 120, 240]) {
    for (const vibes of [["cozy"], ["chaotic"], ["party", "chill"], VIBES.slice(), ["competitive"]]) {
      for (const kids of [false, true]) {
        cases.push({ group_size, minutes, vibes, kids });
      }
    }
  }
}
// Edge cases: system aliases + the honest no-lineup paths.
cases.push(
  { group_size: 4, minutes: 60, vibes: ["party"], kids: false, systems: ["browser"] },
  { group_size: 4, minutes: 60, vibes: ["party"], kids: false, systems: ["web"] },
  { group_size: 4, minutes: 60, vibes: ["party"], kids: false, systems: ["ps1"] },
  { group_size: 4, minutes: 60, vibes: ["party"], kids: false, systems: ["switch", "ps1"] },
  { group_size: 1, minutes: 15, vibes: ["chill"], kids: true },
  { group_size: 12, minutes: 240, vibes: ["chaotic", "competitive"], kids: true }
);

let pass = 0;
let fail = 0;
const failures = [];
for (const inputs of cases) {
  const a = server.pickLineup(inputs, catalog);
  const b = client.pickLineup(inputs, catalog);
  const sa = JSON.stringify(a);
  const sb = JSON.stringify(b);
  if (sa === sb) {
    pass++;
  } else {
    fail++;
    if (failures.length < 3) failures.push({ inputs, server: sa.slice(0, 300), client: sb.slice(0, 300) });
  }
}

// Surface parity: same exported API, same scoring version.
const apiOk =
  server.SCORING_VERSION === client.SCORING_VERSION &&
  JSON.stringify(server.KNOWN_VIBES) === JSON.stringify(client.KNOWN_VIBES) &&
  JSON.stringify(server.WEB_SYSTEM_ALIASES) === JSON.stringify(client.WEB_SYSTEM_ALIASES) &&
  typeof client.scoreGame === "function" &&
  typeof client.gameVibes === "function" &&
  typeof client.multiplayerOk === "function";

console.log("parity cases: " + cases.length + ", pass=" + pass + ", fail=" + fail);
console.log("scoring_version=" + server.SCORING_VERSION + ", surface parity=" + apiOk);
for (const f of failures) console.log("DIVERGENCE", JSON.stringify(f));

if (fail > 0 || !apiOk) {
  console.error("FAIL: server/client game-night divergence");
  process.exit(1);
}
console.log("PARITY OK — client fallback computes exactly what the server would");
