/* ---------- 4. ZIP + DOS round-trips ---------- */
(async () => {
  /* Content identity: same bytes, any name -> same id (saves survive renames). */
  for (const [file] of CONVERT_CASES) {
    const bytes = FIX(file);
    const reader = (arr) => (off, len) => Promise.resolve(arr.slice(off, off + len));
    const id1 = await C4.contentIdFor("test", bytes.length, reader(bytes));
    const id2 = await C4.contentIdFor("test", bytes.length, reader(bytes));
    check("content identity stable for " + file, id1 === id2 && id1.indexOf("bm4-") === 0, id1);
  }
  const nesBytes = FIX("fixture-nes.nes");
  const zipBytes = await C4.zipStore([{ name: "fixture-nes.nes", data: nesBytes }]);
  check("zip signature routes as zip", C4.detect({ name: "games.zip", size: zipBytes.length, head: zipBytes.slice(0, 64) }).kind === "zip", "PK header");
  const entries = C4.zipList(zipBytes);
  check("zip lists its contents", entries.length === 1 && entries[0].name === "fixture-nes.nes", entries.map((e) => e.name).join(","));
  const out = await C4.zipExtract(zipBytes, entries[0]);
  check("zip extract round-trips bytes", out.length === nesBytes.length && out.every((b, i) => b === nesBytes[i]), out.length + " bytes identical");
  const det2 = C4.detect({ name: entries[0].name, size: out.length, head: out.slice(0, 1024) });
  check("zipped game routes onward to play", det2.kind === "play" && det2.core === "nes", det2.kind + "/" + det2.core);

  const folder = C4.detectFolder(["GAME.EXE", "DATA.DAT", "README.TXT"]);
  check("DOS folder recognised", folder.kind === "dos", folder.via);
  check("DOS start program prefers start.bat",
    C4.chooseDosExecutable(["game.exe", "start.bat", "setup.exe"]) === "start.bat", "start wins");
  const conf = C4.dosboxConf("START.BAT", null);
  check("dosbox.conf mounts and runs the start program",
    conf.includes("[autoexec]") && conf.includes("START.BAT"), "config carries the exec");

  /* ---------- 5. COVERAGE agrees with the engines ---------- */
  const cov = JSON.parse(fs.readFileSync(path.join(ROOT, "data/v1/coverage.json"), "utf8"));
  const profileSystems = Object.values(C.PROFILES).map((p) => p.system).sort();
  check("coverage convert == profiles",
    JSON.stringify(cov.convert.map((c) => c.name).sort()) === JSON.stringify(profileSystems),
    cov.convert.length + " profiles");
  check("coverage guide == declines", cov.guide.length === Object.keys(C4.DECLINES).length,
    cov.guide.length + " declines");
  const covFormats = new Set();
  cov.play.forEach((g) => g.formats.forEach((f) => covFormats.add(f)));
  check("coverage play covers every play extension",
    Object.keys(PLAY_EXTS).every((e) => covFormats.has("." + e)), covFormats.size + " formats listed");

  console.log("\n" + pass + " passed, " + fail + " failed");
  process.exit(fail ? 1 : 0);
})().catch((e) => { console.error("HARNESS ERROR", e); process.exit(1); });
